// Writes brand/tokens.css + brand/tokens.json and checks WCAG contrast of every text pairing.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { hex } from "./tokens.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..");

// QoreChain-ecosystem look (owner request, 2026-11-13): the palette and feel of the QoreX wallet,
// never its logo. Values from the owner's brief (navy #12142A to #181A30, cards #1E2036 / #2A2D4A,
// cyan-to-purple gradient #3EF0D2 to #9B4DFF, teal addresses); to be re-sampled from
// brand/reference/qorex-palette.png when that image is added. One dark theme for every visitor.
const qore = {
  paper: "#14162c", "paper-2": "#1a1c34", "paper-3": "#22253f", cotton: "#1e2036", desk: "#101225",
  ink: "#eef0ff", "ink-2": "#cdd0ea", muted: "#a3a7c9",
  rule: "#2a2d4a", "rule-2": "#3b3f63",
  // Teal for addresses, links and the settled state; focus a lighter teal so it shows on every surface.
  settled: "#3ef0d2", link: "#5ff2db", focus: "#8ff7e6", addr: "#3ef0d2",
  // Main action: cyan-to-purple gradient with near-black text (checked against both ends).
  "accent-a": "#3ef0d2", "accent-b": "#9b4dff", "on-accent": "#07081a",
  // Safety colours: never the brand teal or purple. Amber = caution, rose = possible scam / failure.
  warn: "#ffd27a", "warn-bg": "#2d281b", "warn-rule": "#8a6f2e",
  danger: "#ff9aa8", "danger-bg": "#331c2b", "danger-rule": "#b04a63",
  ok: "#7ff2c8", "ok-bg": "#15302e",
};

// ---- WCAG contrast
const lum = (h) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const toHex = (v) => (typeof v === "string" ? v : hex(v));
const ratio = (a, b) => {
  const [x, y] = [lum(toHex(a)), lum(toHex(b))].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const pairs = [
  ["ink", "paper", 4.5], ["ink", "cotton", 4.5], ["ink-2", "paper", 4.5], ["muted", "paper", 4.5], ["muted", "paper-2", 4.5],
  ["settled", "paper", 4.5], ["link", "paper", 4.5], ["focus", "paper", 3],
  ["warn", "warn-bg", 4.5], ["danger", "danger-bg", 4.5], ["ok", "ok-bg", 4.5],
  ["danger", "paper", 4.5], ["warn-rule", "paper", 1.5], ["rule-2", "paper", 1.2],
  ["ink", "paper-3", 4.5], ["ink-2", "cotton", 4.5], ["muted", "cotton", 4.5], ["link", "cotton", 4.5],
  ["addr", "paper", 4.5], ["addr", "cotton", 4.5], ["focus", "cotton", 3],
  ["on-accent", "accent-a", 4.5], ["on-accent", "accent-b", 4.5], ["danger", "cotton", 4.5], ["warn", "paper", 4.5],
];
let fail = 0;
for (const [name, theme] of [["qore", qore]]) {
  for (const [fg, bg, min] of pairs) {
    const r = ratio(theme[fg], theme[bg]);
    const ok = r >= min;
    if (!ok) fail++;
    console.log(`${ok ? "ok  " : "FAIL"} ${name.padEnd(5)} ${fg.padEnd(9)} on ${bg.padEnd(9)} ${r.toFixed(2)} (min ${min})`);
  }
}

const oklch = (v) => (typeof v === "string" ? v : `oklch(${v[0]}% ${v[1]} ${v[2]})`);
const block = (t) => Object.entries(t).map(([k, v]) => `  --color-${k}: ${oklch(v)};`).join("\n");

const css = `/* Qrow design tokens. Generated by brand/src/build-tokens.mjs: Qrow's own logo (B. Return) with the
   QoreChain-ecosystem palette (QoreX's colours, not its marks). Edit the generator, not this file. */
:root {
  color-scheme: dark;
${block(qore)}
  --gradient-accent: linear-gradient(100deg, var(--color-accent-a), var(--color-accent-b));

  /* Type. General Sans (Fontshare, ITF FFL: load from the CDN, never commit the files).
     Arabic: IBM Plex Sans Arabic (SIL OFL). Figures in columns: Geist Mono (SIL OFL). */
  --font-body: "General Sans", ui-sans-serif, system-ui, sans-serif;
  --font-display: var(--font-body);
  --font-arabic: "IBM Plex Sans Arabic", "General Sans", ui-sans-serif, system-ui, sans-serif;
  --font-mono: "Geist Mono", ui-monospace, "SFMono-Regular", monospace;
  --weight-body: 400; --weight-medium: 500; --weight-display: 600;
  --tracking-display: -0.03em;
  --text-xs: 0.8125rem;   /* 13 */
  --text-sm: 0.875rem;    /* 14 */
  --text-base: 1rem;      /* 16 */
  --text-lg: 1.125rem;    /* 18 */
  --text-title: 1.375rem; /* 22 */
  --text-h2: clamp(1.625rem, 1.3rem + 1.2vw, 2.125rem);
  --text-display: clamp(2.25rem, 1.6rem + 2.8vw, 3.75rem);
  --text-figure: clamp(2.5rem, 1.8rem + 3vw, 4rem); /* an amount set as the hero of a screen */
  --leading-tight: 1.05; --leading-snug: 1.25; --leading-body: 1.55;

  /* Space (4px base) */
  --space-2xs: 2px; --space-xs: 4px; --space-sm: 8px; --space-md: 16px; --space-lg: 24px;
  --space-xl: 40px; --space-2xl: 64px; --space-3xl: 96px;
  --container: 1120px; --measure: 62ch; --gutter: 16px;

  /* Radius: one per nesting level */
  --radius-input: 6px; --radius-card: 8px; --radius-sheet: 12px; --radius-pill: 999px;
  --rule-hair: 1px;

  /* Elevation: one light from the left, shadows fall right */
  --shadow-card: 0 1px 2px rgb(4 5 16 / 0.5);
  --shadow-lift: 6px 5px 18px -8px rgb(4 5 16 / 0.6);

  /* Motion: transform and opacity only */
  --dur-short: 140ms; --dur-medium: 240ms; --ease-out: cubic-bezier(0.2, 0.7, 0.2, 1);

  /* Controls */
  --control-h: 48px; --focus-ring: 2px solid var(--color-focus); --focus-offset: 2px;
}

:lang(ar), [dir="rtl"] { --font-body: var(--font-arabic); --tracking-display: 0; }
`;
writeFileSync(join(OUT, "tokens.css"), css);

const json = { qore: {} };
for (const [k, v] of Object.entries(qore)) json.qore[k] = { hex: toHex(v) };
writeFileSync(join(OUT, "tokens.json"), JSON.stringify(json, null, 2) + "\n");
console.log(fail ? `\n${fail} contrast failures` : "\nall contrast pairs pass");
process.exitCode = fail ? 1 : 0;
